import { P, H3, Claim, Pullout } from '../../paper';
import { Pop } from '../wiki';

export default function TheMoth() {
  return (
    <>
      <H3>On “what is the point?”</H3>
      <P>
        Sooner or later someone asks the flat question: so what is the purpose? What is the point of any of it?
      </P>
      <P>
        The quick move is to answer a question with a question. Why do we build things? Why do we bother? Why,
        when we play a game, do we want to win — why not play wanting to lose? And if they object that I am
        answering a question with a question, I can say: you started first.
      </P>
      <P>
        That wins the exchange. But winning the exchange is itself the trap. It is the O(1) answer, the point
        handed over without the walk (<a href="/philosophy/watching-the-split/the-tree" style={{ color: '#60a5fa', textDecoration: 'none' }}>the
        tree</a>), and it leaves the person beaten rather than moved. I would rather leave them curious. So I go
        one level deeper, and I hand them the sharpest version of their own objection, because that is where
        the theory gets interesting and where it earns its keep.
      </P>

      <H3>The challenge, at full strength</H3>
      <Claim label="The knife" color="#fbbf24">
        Grant that the drive to continue — to build, to win, to keep going — is upstream of our reasoning. We
        do not derive it; it is the root the whole tree hangs from. Fine, says the challenger. But a compulsion
        is not a purpose. A moth flies to the flame. Its drive is upstream of its reasoning too, and it is just
        dead matter following a gradient into fire. You have explained why I cannot stop wanting to win. You
        have not shown the wanting is worth anything. You have described a compulsion and dressed it as a
        meaning.
      </Claim>
      <P>
        That blade can draw blood. If there were no answer, the theory would fall right here, and the reader
        should feel that it could.
      </P>

      <H3>The answer: the moth, minus awareness</H3>
      <P>
        The moth is exactly the right picture, because the moth is us with one thing removed: awareness. The
        moth's flame-seeking is a closed loop. It repeats; it does not climb. It is 0.333… repeating for ever:
        infinite, but thin. Strip awareness out of a person and you get precisely that: the drive with no one
        home to witness it.
      </P>
      <P>
        Add awareness back, and the same flame-seeking becomes a <Pop id="up-spiral">spiral</Pop> instead of a
        loop. Now there is someone present to notice the drive, to stand in the <Pop id="to-be">“or”</Pop> between
        wanting and not-wanting, and to fold the loop into a climb. The building begets a thing that begets the
        next question that begets the next building. The drive, unfolded by a witness, generates more than it
        started with. That is richness as unfoldability. A purpose that only closes a loop is the moth. A
        purpose that opens the next fold is a life.
      </P>
      <P>
        So the difference between you and the moth is not the wanting; you share that. It is that you can hear
        yourself ask the question. That is the point. The asking is the climb.
      </P>
      <Pullout>
        And then the compressed form, the one that only unfolds for someone who has walked this far: it is the
        moth, minus awareness.
      </Pullout>

      <H3>Why hand the knife over at all</H3>
      <P>
        Because a theory you cannot imagine failing has stopped being tested, and a challenge I have pre-loaded
        with a safe answer is not a knife, it is a prop. The moth objection is a real kill-shot that the theory
        then survives — survives honestly, by pointing to the one thing the moth lacks. If I soften the
        challenge so my answer looks stronger, I have handed the reader a rubber knife and performed a trick. I
        would rather hand over the real blade, name it as real, and let the reader feel the theory nearly die
        before it stands.
      </P>
      <P>
        That is the whole posture of this writing: here is how you would attack this; that is where it gets
        interesting; that is where it serves its purpose. The reader who leaves curious, holding a real
        challenge, has been handed a tree to walk, not a conclusion to swallow. Transmitted purpose bounces.
        Re-derived purpose lands.
      </P>
    </>
  );
}
